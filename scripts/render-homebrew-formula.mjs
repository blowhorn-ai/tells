#!/usr/bin/env node
// Renders the Homebrew formula for the tells command from schemas/cli-release.json.
// The blowhorn-ai/homebrew-tap update workflow runs this file from a checkout of this repo,
// so the manifest stays the only place the package, tap and formula names live.
//
//   node scripts/render-homebrew-formula.mjs --version 0.3.12 --sha256 <hex> [--out Formula/tells.rb]
//   node scripts/render-homebrew-formula.mjs --from-npm [--out Formula/tells.rb]
//
// --from-npm reads the latest version and tarball from the public npm registry, checks the
// tarball against the registry's sha512 integrity, and uses its sha256 (Homebrew wants sha256).
// With --out, stdout is one line, "<formula> <version>", for the tap's commit message.

import { createHash } from "node:crypto";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname } from "node:path";
import { pathToFileURL } from "node:url";
import { parseArgs } from "node:util";
import { assertVersion } from "./release-version.mjs";

const MANIFEST_URL = new URL("../schemas/cli-release.json", import.meta.url);
const SHA256_HEX = /^[0-9a-f]{64}$/;

export function loadManifest() {
  return JSON.parse(readFileSync(MANIFEST_URL, "utf8"));
}

export function tarballUrl(manifest, version) {
  const name = manifest.package.name;
  return `${manifest.npm.registry}/${name}/-/${name}-${assertVersion(version)}.tgz`;
}

// Homebrew's Formulary class name rule for the characters the schema allows: tells -> Tells, foo-bar -> FooBar.
export function formulaClassName(formula) {
  return formula.replace(/(?:^|-)([a-z0-9])/g, (_, ch) => ch.toUpperCase());
}

// What the formula means, independent of Ruby syntax. renderFormula is a pure function of this.
export function formulaModel(manifest, { version, sha256 }) {
  if (typeof sha256 !== "string" || !SHA256_HEX.test(sha256)) {
    throw new Error(`sha256 must be 64 lowercase hex characters, got ${JSON.stringify(sha256)}`);
  }
  const { homebrew } = manifest;
  return {
    formula: homebrew.formula,
    className: formulaClassName(homebrew.formula),
    desc: homebrew.desc,
    homepage: manifest.package.homepage,
    url: tarballUrl(manifest, version),
    sha256,
    license: manifest.package.license,
    dependsOn: [...homebrew.depends_on],
    // npm installs the package into libexec; every bin it declares is linked into Homebrew's bin.
    install: { npmPackage: manifest.package.name, linkBins: [manifest.package.bin] },
    test: { command: manifest.package.bin, args: ["--help"], expectOutput: "Usage:" }
  };
}

function rubyString(value) {
  return `"${String(value).replace(/[\\"#]/g, (ch) => `\\${ch}`)}"`;
}

export function renderFormula(model) {
  const testCommand = [`#{bin}/${model.test.command}`, ...model.test.args].join(" ");
  return [
    "# Generated by scripts/render-homebrew-formula.mjs in https://github.com/blowhorn-ai/tells",
    "# from schemas/cli-release.json. Do not edit by hand; the update-formula workflow rewrites it.",
    `class ${model.className} < Formula`,
    `  desc ${rubyString(model.desc)}`,
    `  homepage ${rubyString(model.homepage)}`,
    `  url ${rubyString(model.url)}`,
    `  sha256 ${rubyString(model.sha256)}`,
    `  license ${rubyString(model.license)}`,
    "",
    ...model.dependsOn.map((dep) => `  depends_on ${rubyString(dep)}`),
    "",
    "  def install",
    '    system "npm", "install", *std_npm_args',
    '    bin.install_symlink libexec.glob("bin/*")',
    "  end",
    "",
    "  test do",
    // shell_output also asserts exit status 0.
    `    assert_match ${rubyString(model.test.expectOutput)}, shell_output("${testCommand}")`,
    "  end",
    "end",
    ""
  ].join("\n");
}

async function fetchOk(fetchImpl, url, what) {
  let response;
  try {
    response = await fetchImpl(url, { signal: AbortSignal.timeout(30_000) });
  } catch (error) {
    throw new Error(`GET ${url} (${what}) failed: ${error instanceof Error ? error.message : error}`);
  }
  if (!response.ok) throw new Error(`GET ${url} (${what}) returned ${response.status}`);
  return response;
}

// Latest published version plus the sha256 of its tarball, verified against the registry's sha512.
export async function fetchLatestRelease(manifest, fetchImpl = globalThis.fetch) {
  const metaUrl = `${manifest.npm.registry}/${manifest.package.name}/latest`;
  const meta = await (await fetchOk(fetchImpl, metaUrl, "package metadata")).json();
  const version = assertVersion(meta?.version);
  const expectedTarball = tarballUrl(manifest, version);
  if (meta.dist?.tarball !== expectedTarball) {
    throw new Error(`Registry tarball ${JSON.stringify(meta.dist?.tarball)} is not ${expectedTarball}`);
  }
  const integrity = /^sha512-([A-Za-z0-9+/]+={0,2})$/.exec(meta.dist?.integrity ?? "");
  if (!integrity) throw new Error(`Registry integrity for ${version} is not a sha512 SRI string`);

  const tarball = Buffer.from(await (await fetchOk(fetchImpl, expectedTarball, "tarball")).arrayBuffer());
  if (createHash("sha512").update(tarball).digest("base64") !== integrity[1]) {
    throw new Error(`Tarball ${expectedTarball} does not match the registry sha512 integrity`);
  }
  return { version, sha256: createHash("sha256").update(tarball).digest("hex") };
}

export async function main(argv, { fetchImpl = globalThis.fetch, stdout = process.stdout, manifest = loadManifest() } = {}) {
  const { values } = parseArgs({
    args: argv,
    strict: true,
    allowPositionals: false,
    options: {
      version: { type: "string" },
      sha256: { type: "string" },
      "from-npm": { type: "boolean" },
      out: { type: "string" }
    }
  });
  const fromNpm = values["from-npm"] === true;
  if (fromNpm === (values.version !== undefined || values.sha256 !== undefined)) {
    throw new Error("Pass either --from-npm, or both --version and --sha256.");
  }
  const release = fromNpm ? await fetchLatestRelease(manifest, fetchImpl) : { version: values.version, sha256: values.sha256 };
  const formula = renderFormula(formulaModel(manifest, release));
  if (values.out === undefined) {
    stdout.write(formula);
  } else {
    mkdirSync(dirname(values.out), { recursive: true });
    writeFileSync(values.out, formula);
    stdout.write(`${manifest.homebrew.formula} ${release.version}\n`);
  }
  return release;
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? "").href) {
  try {
    await main(process.argv.slice(2));
  } catch (error) {
    process.stderr.write(`${error instanceof Error ? error.message : error}\n`);
    process.exit(1);
  }
}
